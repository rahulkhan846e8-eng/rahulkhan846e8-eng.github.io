// In-memory cache for full anime details loaded on demand
const fullAnimeCache = new Map();

/**
 * Synchronous summary lookup from 110KB catalog
 */
export function getAnimeSummary(id) {
  if (!id) return null;
  const clean = id.toLowerCase().trim();
  return ANIME_CATALOG.find(item => item.id === clean || item.id === clean.replace(/\s+/g, '-')) || null;
}

/**
 * Asynchronously loads complete episode playlist and download links on demand.
 * Uses dynamic import so data.js (3.5MB) is NEVER downloaded on initial page load!
 */
export async function getFullAnimeDetails(id) {
  if (!id) return null;
  const clean = id.toLowerCase().trim();
  const cacheKey = clean.replace(/\s+/g, '-');

  if (fullAnimeCache.has(cacheKey)) {
    return fullAnimeCache.get(cacheKey);
  }

  try {
    const { ANIME_DATABASE } = await import('./data.js');
    for (const anime of ANIME_DATABASE) {
      const key = (anime.id || "").toLowerCase().trim();
      fullAnimeCache.set(key, anime);
      if (key.includes('-')) {
        fullAnimeCache.set(key.replace(/-/g, ' '), anime);
      }
    }
    return fullAnimeCache.get(cacheKey) || getAnimeSummary(id);
  } catch (err) {
    console.error("Failed to dynamically load full anime details:", err);
    return getAnimeSummary(id);
  }
}

export function getNewlyAddedAnime() {
  return ANIME_CATALOG.slice(0, 16);
}

export function getPopularAnime() {
  const popularMap = new Map();
  for (const id of FAMOUS_POPULAR_IDS) {
    const anime = ANIME_CATALOG.find(item => item.id === id);
    if (anime) popularMap.set(anime.id, anime);
  }
  for (const item of ANIME_CATALOG) {
    if (item.isPopular && !popularMap.has(item.id)) {
      popularMap.set(item.id, item);
    }
  }
  return Array.from(popularMap.values());
}

export function getActionAnime() {
  return ANIME_CATALOG.filter(item => 
    item.genres?.some(g => g.toLowerCase().includes('action') || g.toLowerCase().includes('adventure'))
  ).slice(0, 16);
}

export function getTopRatedAnime() {
  return [...ANIME_CATALOG].sort((a, b) => (b.rating || 0) - (a.rating || 0)).slice(0, 16);
}

export function getMovies() {
  return ANIME_CATALOG.filter(item => item.type === 'Movie');
}

export function searchAnime(query = "", genre = "All", type = "All", sortBy = "popularity") {
  let list = [...ANIME_CATALOG];

  if (genre && genre !== "All") {
    list = list.filter(item => item.genres?.some(g => g.toLowerCase().includes(genre.toLowerCase())));
  }

  if (type && type !== "All") {
    list = list.filter(item => item.type?.toLowerCase() === type.toLowerCase());
  }

  if (query && query.trim()) {
    const q = query.toLowerCase().trim();
    list = list.filter(item => 
      item.title?.toLowerCase().includes(q) ||
      item.japaneseTitle?.toLowerCase().includes(q) ||
      item.raw_name?.toLowerCase().includes(q) ||
      item.genres?.some(g => g.toLowerCase().includes(q))
    );
  }

  if (sortBy === "rating") {
    list.sort((a, b) => (b.rating || 0) - (a.rating || 0));
  } else if (sortBy === "year") {
    list.sort((a, b) => (b.year || 0) - (a.year || 0));
  } else if (sortBy === "title") {
    list.sort((a, b) => a.title.localeCompare(b.title));
  } else {
    // popularity default
    list.sort((a, b) => (b.isPopular ? 1 : 0) - (a.isPopular ? 1 : 0));
  }

  return list;
}
